// Builds worker/recipe-reader.js: assets/lib.js plus worker/handler.js in one file, ready to
// paste into the Cloudflare dashboard. Run `npm run build:worker` after changing either source.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function build() {
  const lib = readFileSync(join(root, 'assets', 'lib.js'), 'utf8');
  const handler = readFileSync(join(root, 'worker', 'handler.js'), 'utf8');
  return `// GENERATED by tools/build-worker.mjs from assets/lib.js and worker/handler.js. Do not edit.\n${lib}\n${handler}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'worker', 'recipe-reader.js'), build());
  console.log('Wrote worker/recipe-reader.js');
}
